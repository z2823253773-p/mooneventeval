"""Development-only exhaustive partial-injection oracle, not augmenting paths."""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
import random
import subprocess

SEED = 20261020


def max_cardinality(adjacency: list[list[int]], prediction_count: int) -> int:
    """Enumerate every legal partial injection; no pruning or matching algorithm."""
    best = 0

    def visit(reference: int, used: frozenset[int], count: int) -> None:
        nonlocal best
        if reference == len(adjacency):
            best = max(best, count)
            return
        visit(reference + 1, used, count)  # This reference is unmatched.
        for prediction in adjacency[reference]:
            if prediction not in used:
                visit(reference + 1, used | {prediction}, count + 1)

    if prediction_count < 0 or any(
        row != sorted(set(row)) or any(p < 0 or p >= prediction_count for p in row)
        for row in adjacency
    ):
        raise ValueError("expected ascending unique in-range prediction indices")
    visit(0, frozenset(), 0)
    return best


def cases() -> list[dict]:
    result = []
    for references in range(4):
        for predictions in range(4):
            for mask in range(1 << (references * predictions)):
                graph = [
                    [p for p in range(predictions) if mask & (1 << (r * predictions + p))]
                    for r in range(references)
                ]
                result.append({"id": f"all-{references}-{predictions}-{mask}",
                               "adjacency": graph, "prediction_count": predictions,
                               "expected": max_cardinality(graph, predictions)})
    rng = random.Random(SEED)
    for references in range(4, 8):
        for predictions in range(4, 8):
            for probability in (0.2, 0.4, 0.6, 0.8):
                graph = [[p for p in range(predictions) if rng.random() < probability]
                         for _ in range(references)]
                result.append({"id": f"seed-{references}-{predictions}-{probability}",
                               "adjacency": graph, "prediction_count": predictions,
                               "expected": max_cardinality(graph, predictions)})
    return result


def emit_mbt(path: Path, cases_json: Path | None = None) -> None:
    source_hash = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
    fixtures = cases()
    lines = ["// Generated by validation/graph_oracle.py; do not hand edit.",
             f"// generator_sha256: {source_hash}",
             f"// seed: {SEED}; exhaustive 0..3 each side: 689; seeded 4..7: 64.",
             "", "///|", 'test "matching_oracle_exhaustive_and_seeded" {']
    for item in fixtures:
        graph = json.dumps(item["adjacency"])
        lines += [f'  // {item["id"]}',
                  f'  record_matching_case("{item["id"]}", check_matching({graph}, {item["prediction_count"]}, {item["expected"]}))']
    lines += ["}", ""]
    path.write_text("\n".join(lines))
    # Normalize with the locked formatter so regeneration and moon fmt agree.
    root = Path(__file__).resolve().parents[1]
    subprocess.run([str(root / 'scripts/with-toolchain.sh'), 'moonfmt', '-w', str(path)],
                   check=True)
    # Complete immutable inputs/expectations, not just a fixture count.
    if cases_json is not None:
        cases_json.write_text(json.dumps({
            "generator_sha256": source_hash, "seed": SEED, "cases": fixtures,
        }, indent=2) + "\n")
    print(json.dumps({"cases": len(fixtures), "seed": SEED,
                      "generator_sha256": source_hash, "output": str(path)}))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--emit-mbt', type=Path, required=True)
    parser.add_argument('--cases-json', type=Path)
    args = parser.parse_args()
    emit_mbt(args.emit_mbt, args.cases_json)
